--    • баны        bans               (тестовые блокировки)
--    • личное      private_user_state (кэш «мои/мои заявки» на пользователя)
--    • лимиты      rate_events        (журнал — иначе тестеры упрутся в
--                                      лимиты в первый день релиза)
--    • фото        storage photos/chat_photos (все файлы в бакетах)
--
--  НЕ трогает:
--    • auth.users  — аккаунты остаются, профили к ним поднимутся заново.
--      Если нужен ПОЛНЫЙ сброс (чтобы все заново регистрировались) —
--      см. блок "ПОЛНЫЙ СБРОС АККАУНТОВ" в конце (закомментирован).
--    • moderators  — список модераторов (админ-доступ) сохраняется.
--    • сами бакеты photos/chat_photos — очищаются файлы, бакеты остаются.
--
--  ⚠️ НЕОБРАТИМО. Перед запуском — бэкап:
--      pg_dump --data-only > backup_pre_release.sql
--  Запуск: docker exec -i supabase-db psql -U postgres -d postgres < файл
--
--  ВАЖНО про клиентские устройства: после очистки сервера приложение на
--  устройстве само заново зальёт СВОЙ профиль (_pullRemote upsert'ит
--  меня). Старые заявки из локального кэша НЕ воскреснут (после успешной
--  синхронизации их нет в _pendingJobSync). Чтобы старт был совсем
--  чистым — на тестовых устройствах очистите данные приложения
--  (веб: «Очистить данные сайта»; Android: удалить данные приложения;
--  iOS/ПК: переустановить или удалить данные).
-- ============================================================

begin;

-- --- 1. Заявки и всё, что к ним привязано -------------------------
-- shared_jobs, job_locations, messages связаны FK/RLS-логикой:
-- чистим потомков раньше родителей.
delete from public.job_locations;
delete from public.messages;
delete from public.shared_jobs;

-- --- 2. Социальный слой -------------------------------------------
delete from public.reviews;
delete from public.reports;
delete from public.shared_profiles;
delete from public.bans;
delete from public.private_user_state;

-- --- 3. Лимиты: сброс журнала (иначе лимиты 3/70 заявок и 10 откликов
--      не сбросятся, и новые пользователи упрутся в них в первый день).
--      Триггеры и таблица rate_events остаются, чистим только строки.
delete from public.rate_events;

-- --- 4. Фото в Storage --------------------------------------------
-- Сначала очищаем бакеты с файлами, потом таблицу объектов.
delete from storage.objects where bucket_id in ('photos', 'chat_photos');

commit;

