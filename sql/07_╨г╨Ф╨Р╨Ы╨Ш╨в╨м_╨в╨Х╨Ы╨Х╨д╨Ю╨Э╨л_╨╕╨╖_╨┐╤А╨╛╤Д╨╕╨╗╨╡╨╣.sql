-- ============================================================
--  ОДНОРАЗОВАЯ ОЧИСТКА: убрать телефоны из общей базы профилей
--  Запустить в Supabase -> SQL Editor -> Run.
--
--  Начиная с v40.7 приложение больше НЕ рассылает телефон всем
--  пользователям (его нельзя больше "выкачать" через консоль браузера).
--  Пользователи сами делятся номером в чате, если хотят созвониться.
--
--  Этот скрипт удаляет телефоны, которые уже успели попасть в базу
--  раньше. Запускать один раз. Свой номер у каждого остаётся локально
--  на устройстве и в форме профиля.
-- ============================================================

update public.shared_profiles
set data = data - 'phone'
where data ? 'phone';

