/// Офлайн-справочник городов России: название, регион и координаты центра.
///
/// Используется для:
///  • выбора города при регистрации и в профиле (поиск с живыми совпадениями);
///  • центрирования карты на выбранном городе;
///  • сортировки ленты «свой город → ближайшие города».
///
/// Данные вшиты в приложение — работает без интернета и без новых зависимостей.
class RuCity {
  final String name;
  final String region;
  final double lat;
  final double lng;

  const RuCity(this.name, this.region, this.lat, this.lng);

  /// «Уфа, Башкортостан» — для подписи в списке подсказок.
  String get label => region.isEmpty || region == name ? name : '$name, $region';

  @override
  String toString() => label;
}

/// Приводит строку к виду для сравнения: нижний регистр, ё → е, ъь и дефисы
/// не мешают поиску («нижнийновгород» найдёт «Нижний Новгород»).
String normalizeCity(String s) {
  final lower = s.toLowerCase().replaceAll('ё', 'е').trim();
  final buf = StringBuffer();
  for (final ch in lower.split('')) {
    if (ch == ' ' || ch == '-' || ch == '.' || ch == ',') continue;
    buf.write(ch);
  }
  return buf.toString();
}

class RuCities {
  RuCities._();

  static List<RuCity>? _cache;
  static Map<String, RuCity>? _index;

  /// Все города, отсортированы по убыванию численности населения.
  static List<RuCity> get all {
    final cached = _cache;
    if (cached != null) return cached;
    final list = <RuCity>[];
    for (final row in _raw.split('\n')) {
      final line = row.trim();
      if (line.isEmpty) continue;
      final parts = line.split('|');
      if (parts.length != 4) continue;
      final lat = double.tryParse(parts[2]);
      final lng = double.tryParse(parts[3]);
      if (lat == null || lng == null) continue;
      list.add(RuCity(parts[0], parts[1], lat, lng));
    }
    _cache = list;
    return list;
  }

  static Map<String, RuCity> get _byNormalizedName {
    final cached = _index;
    if (cached != null) return cached;
    final map = <String, RuCity>{};
    for (final c in all) {
      map.putIfAbsent(normalizeCity(c.name), () => c);
    }
    _index = map;
    return map;
  }

  /// Точный поиск по названию (для сохранённого в профиле города).
  static RuCity? byName(String name) {
    if (name.trim().isEmpty) return null;
    return _byNormalizedName[normalizeCity(name)];
  }

  /// Координаты города по названию. null, если город неизвестен.
  static ({double lat, double lng})? coordsOf(String name) {
    final c = byName(name);
    if (c == null) return null;
    return (lat: c.lat, lng: c.lng);
  }

  /// Живой поиск совпадений. Пустой запрос → первые [limit] крупнейших городов.
  ///
  /// Ранжирование:
  ///  0 — название начинается с запроса («уфа» → Уфа);
  ///  1 — с запроса начинается второе слово («новгород» → Нижний Новгород);
  ///  2 — запрос встречается внутри названия;
  ///  3 — совпал регион («башкорт» → все города Башкортостана).
  /// Внутри одной группы порядок — по величине города.
  static List<RuCity> search(String query, {int limit = 40}) {
    final q = normalizeCity(query);
    if (q.isEmpty) return all.take(limit).toList();

    final scored = <({int rank, int order, RuCity city})>[];
    for (var i = 0; i < all.length; i++) {
      final city = all[i];
      final name = normalizeCity(city.name);
      int? rank;
      if (name.startsWith(q)) {
        rank = 0;
      } else {
        final words = city.name.toLowerCase().replaceAll('ё', 'е').split(RegExp(r'[\s\-]+'));
        if (words.skip(1).any((w) => w.startsWith(q))) {
          rank = 1;
        } else if (name.contains(q)) {
          rank = 2;
        } else if (normalizeCity(city.region).contains(q)) {
          rank = 3;
        }
      }
      if (rank != null) scored.add((rank: rank, order: i, city: city));
    }

    scored.sort((a, b) {
      final byRank = a.rank.compareTo(b.rank);
      if (byRank != 0) return byRank;
      return a.order.compareTo(b.order);
    });
    return scored.take(limit).map((e) => e.city).toList();
  }

  /// Ближайший город к точке. Нужен для старых заявок, у которых ещё нет
  /// поля city — город определяется по координатам метки.
  ///
  /// [maxKm] — максимальное удаление; дальше считаем, что город не определён.
  static RuCity? nearest(double lat, double lng, {double maxKm = 100}) {
    RuCity? best;
    var bestKm = double.infinity;
    for (final c in all) {
      // Грубая отсечка по градусам — сильно дешевле гаверсинуса.
      if ((c.lat - lat).abs() > 2.0) continue;
      if ((c.lng - lng).abs() > 4.0) continue;
      final dLat = (c.lat - lat) * 111.0;
      final dLng = (c.lng - lng) * 111.0 * 0.6;
      final km = dLat * dLat + dLng * dLng;
      if (km < bestKm) {
        bestKm = km;
        best = c;
      }
    }
    if (best == null) return null;
    return bestKm <= maxKm * maxKm ? best : null;
  }

